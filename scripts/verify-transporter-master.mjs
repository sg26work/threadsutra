import { chromium } from 'playwright';

const baseUrl = process.env.TRANSPORTER_TEST_URL || 'http://127.0.0.1:3005';
const uniqueCode = String(Date.now()).slice(-9);
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const exactLabel = (page, text, index = 0) => page.locator('label').filter({ hasText: new RegExp(`^${text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?:\\s|$)`) }).nth(index);
const input = (page, text, index = 0) => exactLabel(page, text, index).locator('input');
const select = (page, text, index = 0) => exactLabel(page, text, index).locator('select');

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const pageErrors = [];
page.setDefaultTimeout(10_000);
page.on('pageerror', (error) => pageErrors.push(error.message));
try {
  await page.addInitScript(() => localStorage.setItem('vin_user', JSON.stringify({ username: 'transporter-e2e' })));
  await page.goto(`${baseUrl}/app/transporters`, { waitUntil: 'domcontentloaded', timeout: 10_000 });
  await page.getByRole('button', { name: 'add new' }).click();
  for (const tab of ['Transporter Details', 'User Defined Field']) await assert(await page.getByRole('button', { name: tab, exact: true }).count() === 1, `Missing tab: ${tab}`);
  for (const label of ['Transporter Type','Transporter Code','Transporter Name','Company Name','GL Code','Validate Service Loc','Send Ship Mail Id','Reverse Validate Service Loc','Delivery Mode','Upload AWB series','Is Active','Tracking Hour Less than 24 hr','Dimensional Factor','TransType','isDriverMandatory','OTP Flag','Secure Shipping Flag','Enable Location Linking','GSTIN/CIN','Invoice Generation Before AWB','Min Weight(KG)','Max Weight(KG)','Enable COD Limit','COD Amount','COD Limit For Return','Address 1','Address 2','Address 3','Address 4','Phone','Alternate Phone','Fax','Email','Alternate Email','Country','State','City','Pincode']) await page.getByLabel(label, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Audit', exact: true }).click();
  const audit = page.getByRole('dialog', { name: 'Audit', exact: true });
  for (const label of ['Created By', 'Created Date', 'Modified By', 'Modified Date']) await audit.getByText(label, { exact: true }).waitFor();
  await audit.getByRole('button', { name: 'Close audit' }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('alert').getByText('Please Select Transport Type', { exact: true }).waitFor();
  await assert(await select(page, 'Transporter Type').locator('option').count() === 252, 'Transporter Type catalog differs from LIVE');
  await select(page, 'Transporter Type').selectOption({ label: 'Delhivery (Recommended)' });
  await page.getByRole('button', { name: 'Configure API Details', exact: true }).click();
  for (const label of ['AWB Generation Type','Multi Box Support','Exchange / Replacement Order Support','Min OTP Amount','Create Return on RTO (WMS)','Create Return on RTO (SP)','External Invoice','External Shipping Label','Applicable To B2B','Enable QR Generation','Enable Tracking','Secret Key','Tracking Enable Mongo(Y/N)','Technical Aggregator','Ext Carrier Id','Ext Carrier Name','Ext Reverse Carrier Id','Ext Reverse Carrier Name']) await page.getByLabel(label, { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Transporter Details', exact: true }).click();
  await page.getByLabel('Enable Location Linking', { exact: true }).check();
  await page.getByRole('button', { name: 'Linked Location', exact: true }).click();
  for (const heading of ['Location Code','Location Name','Location Type']) await page.getByRole('columnheader', { name: heading, exact: true }).waitFor();
  const linkedPager = await page.locator('select[title="Records per Page"]').evaluateAll((selects) => selects.map((select) => [...select.options].map((option) => option.textContent)).find((options) => options[0] === '15'));
  assert(JSON.stringify(linkedPager) === JSON.stringify(['15','25','50','200']), 'Linked Location paging differs from LIVE');
  await page.getByRole('button', { name: 'Transporter Details', exact: true }).click();
  await page.getByLabel('Enable Location Linking', { exact: true }).uncheck();
  await input(page, 'Transporter Code').fill(uniqueCode);
  await input(page, 'Transporter Name').fill('Transporter Master E2E');
  await input(page, 'Address 1').fill('77 Dispatch Road');
  await input(page, 'Address 2').fill('Dock B');
  await assert(await select(page, 'Country').locator('option').count() === 281, 'Transporter Country catalog differs from LIVE');
  await assert(await select(page, 'State').locator('option').count() === 500, 'Transporter State catalog differs from LIVE');
  await select(page, 'Country').selectOption({ label: 'INDIA' });
  await select(page, 'State').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'User Defined Field', exact: true }).click();
  await input(page, 'UDF1').fill('retained');
  await page.getByRole('button', { name: 'Transporter Details', exact: true }).click();
  await assert(await input(page, 'Transporter Code').inputValue() === uniqueCode, 'Tab switch reset transporter state');
  const create = page.waitForResponse((response) => response.url().includes('/api/transporters') && response.request().method() === 'POST' && response.status() === 201);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const transporter = await (await create).json();
  await assert(transporter.transporter_code === uniqueCode && transporter.address1 === '77 Dispatch Road', 'Transporter create did not persist UI data');
  await page.getByText('Transporter created successfully').waitFor();
  await page.getByRole('button', { name: 'Close vendor editor' }).click();
  await page.getByRole('button', { name: uniqueCode, exact: true }).waitFor();
  await page.getByRole('button', { name: uniqueCode, exact: true }).click();
  await input(page, 'Transporter Name').fill('Transporter Master E2E Updated');
  const update = page.waitForResponse((response) => response.url().includes('/api/transporters') && response.request().method() === 'PUT' && response.status() === 200);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await assert((await (await update).json()).transporter_name === 'Transporter Master E2E Updated', 'Transporter edit did not persist');
  await page.getByText('Transporter updated successfully').waitFor();
  await assert(pageErrors.length === 0, `Browser page errors: ${pageErrors.join('; ')}`);
  console.log(`Transporter Master browser workflow passed: ${uniqueCode}`);
} catch (error) {
  console.error('Transporter Master browser workflow failed:', error);
  process.exitCode = 1;
} finally {
  await browser.close();
}
