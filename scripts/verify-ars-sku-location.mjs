import { chromium } from 'playwright';

const baseUrl = process.env.ERETAIL_BASE_URL || 'http://127.0.0.1:3011';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
page.on('response', (response) => { if (response.url().includes('/api/') && response.status() >= 500) errors.push(`${response.status()} ${response.url()}`); });
const toast = (text) => page.getByText(text, { exact: true }).waitFor();
const open = async () => { await page.goto(`${baseUrl}/app/procurement/ars/sku-location`, { waitUntil: 'domcontentloaded' }); await page.getByText('No records to view', { exact: true }).waitFor(); };

try {
  await page.goto(baseUrl);
  await page.evaluate(() => localStorage.setItem('vin_user', JSON.stringify({ username: 'ars-link-verifier' })));
  await open();
  const expected = ['Location', 'SKU', 'Category', 'Brand', 'Primary Vendor', 'Fullfillment Method', 'Fullfillment WH', 'WH Lead Time', 'Stock cover days', 'Minimum Transfer Qty', 'Transfer Unit Factor', 'ARS Flag', '', 'Maximum SKU Qty'];
  const headers = (await page.locator('thead tr').first().locator('th').allTextContents()).map((x) => x.trim());
  if (JSON.stringify(headers) !== JSON.stringify(expected)) throw new Error(`Headers mismatch: ${JSON.stringify(headers)}`);
  if ((await page.getByLabel('Records per Page').locator('option').allTextContents()).join() !== '20,50,100,200') throw new Error('Page sizes mismatch.');

  const locationSearch = page.getByLabel('Location search');
  const firstLocation = await locationSearch.locator('option').first().getAttribute('value');
  await locationSearch.selectOption([firstLocation]);
  const searchRequestPromise = page.waitForRequest((request) => request.url().endsWith('/api/fetchArsAttributes'));
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  const searchRequest = await searchRequestPromise;
  const searchPayload = searchRequest.postDataJSON();
  const searchResult = await (await searchRequest.response()).json();
  if (searchPayload.location !== firstLocation || searchPayload.rows !== 20 || searchPayload.page !== 1 || searchPayload.clientId !== '0' || searchPayload.REQ_SEARCH_FLAG !== true || !Array.isArray(searchResult.gridModel) || !('records' in searchResult) || !('total' in searchResult)) throw new Error('Search contract mismatch.');
  await page.getByRole('button', { name: 'Advance Search' }).click();
  await page.getByLabel('SKU Name search').fill('reset-me');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  if (await page.getByLabel('SKU Name search').count()) throw new Error('Reset did not close advanced search.');
  await page.getByRole('button', { name: 'Download', exact: true }).click();
  await toast('No data in grid to export');

  const skus = await (await page.request.get(`${baseUrl}/api/skus`)).json();
  const locationData = await (await page.request.get(`${baseUrl}/api/locations`)).json();
  const existing = await (await page.request.get(`${baseUrl}/api/ars?entity=links`)).json();
  const location = locationData.rows[0];
  const sku = skus.find((candidate) => !existing.some((row) => row.sku_code === candidate.sku_code && (row.location_id === location.location_code || row.location === location.location_name)));
  if (!sku || !location) throw new Error('No non-duplicate test pair.');
  await page.getByRole('button', { name: 'Add New', exact: true }).click();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await toast('SkuCode is mandatory');
  await page.getByLabel('SKU', { exact: true }).fill(sku.sku_code);
  await page.getByLabel('Location', { exact: true }).selectOption(location.location_code);
  await page.getByLabel('Fullfillment Method', { exact: true }).selectOption('Distribution Center');
  await page.getByLabel('ARS Flag', { exact: true }).selectOption('1');
  await page.getByLabel('Stock cover days', { exact: true }).fill('8');
  const addRequestPromise = page.waitForRequest((request) => request.url().endsWith('/api/addAndUpdateArsAttributes'));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const addPayload = (await addRequestPromise).postDataJSON();
  if (addPayload.skuCode !== sku.sku_code || addPayload.location !== location.location_code || addPayload.arsFlag !== '1' || addPayload.minimumTransferQty !== '1.00' || addPayload.transferUnitFactor !== '1.00') throw new Error('Add payload mismatch.');
  await toast('ARS Data Adding/Updating in Grid');

  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByLabel('SKU search').fill(sku.sku_code);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  const row = page.locator('tbody tr').filter({ hasText: sku.sku_code }).first();
  await row.waitFor();
  await row.locator('button').click();
  await page.getByLabel('Stock cover days', { exact: true }).fill('9');
  const updateRequestPromise = page.waitForRequest((request) => request.url().endsWith('/api/addAndUpdateArsAttributes'));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  if (!(await updateRequestPromise).postDataJSON().id) throw new Error('Edit payload omitted row id.');
  await toast('Data Updated successfully.');
  await open();
  await page.getByLabel('SKU search').fill(sku.sku_code);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: sku.sku_code }).filter({ hasText: '9' }).waitFor();

  await page.getByRole('button', { name: 'Bulk Update', exact: true }).click();
  await page.getByRole('button', { name: 'Update', exact: true }).click();
  await toast('Location Type is mandatory');
  await page.getByLabel('Location Type').selectOption('2');
  await page.getByRole('button', { name: 'Update', exact: true }).click();
  await toast('Select at least one attribute to update');
  await page.getByLabel('Update Stock Cover Days', { exact: true }).check();
  const bulkInputs = page.getByText('Update Filter', { exact: true }).locator('xpath=following::label[normalize-space(.)="Stock Cover Days"][1]//input');
  await bulkInputs.last().fill('10');
  const bulkRequestPromise = page.waitForRequest((request) => request.url().endsWith('/api/bulkUpdateArsAttributes'));
  await page.getByRole('button', { name: 'Update', exact: true }).click();
  const bulkPayload = (await bulkRequestPromise).postDataJSON();
  if (bulkPayload.locationType_bulk !== '2' || bulkPayload.stockCoverDaysCheckBox !== true || bulkPayload.stockCoverDays_bulk !== '10') throw new Error('Bulk payload mismatch.');
  await page.getByText(/ARS Location Link updated successfully/).waitFor();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByLabel('SKU search').fill(sku.sku_code);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.locator('tbody tr').filter({ hasText: sku.sku_code }).filter({ hasText: '10' }).waitFor();

  const downloadRequestPromise = page.waitForRequest((request) => request.url().endsWith('/api/downloadArsAttribute'));
  await page.getByRole('button', { name: 'Download', exact: true }).click();
  const downloadPayload = (await downloadRequestPromise).postDataJSON();
  if (downloadPayload.sku !== sku.sku_code || downloadPayload.REQ_SEARCH_FLAG !== true) throw new Error('Download payload mismatch.');
  await page.waitForURL(/\/app\/admin\/exports/);
  await open();
  await page.getByRole('button', { name: 'Bulk Import', exact: true }).click();
  await page.waitForURL(/common-import\?externalImportType=33/);
  if (errors.length) throw new Error(`Console/API errors: ${errors.join(' | ')}`);
  console.log('PASS ARS SKU-Location Link: exact grid, live search payload, reset/advanced, add-edit-bulk persistence, download/report, import routing, pagination, and clean runtime.');
} finally { await browser.close(); }
